"""Compile user-provided alternate-history schedules, without inventing scores/venues."""
import csv, datetime, hashlib, json, pathlib, re
ROOT=pathlib.Path(__file__).resolve().parents[1]
SOURCE=ROOT/'data/sources'
def fixture(season,date,label,opponent,venue=None):
    datetime.date.fromisoformat(date)
    if label.startswith('ラ・リーガ'): competition='La Liga'
    elif label.startswith('CL'): competition='Champions League'
    elif label.startswith('コパ'): competition='Copa del Rey'
    elif label.startswith('スーペルコパ'): competition='Supercopa'
    elif label.startswith('UEFA'): competition='UEFA Super Cup'
    elif label.startswith('FIFAインター'): competition='FIFA Intercontinental Cup'
    else: competition='FIFA Club World Cup'
    digest=hashlib.sha256(f'{season}|{date}|{label}|{opponent}'.encode()).hexdigest()[:12]
    match=re.search(r'第(\d+)節',label)
    return dict(id=f'history-{season}-{digest}',season=season,team='club',date=date,
                competition=competition,stage=label,round=int(match[1]) if match else None,
                opponent=opponent,home=venue=='H',neutral=venue not in [None,'H','A'],
                venueUnknown=venue is None,venue=venue,locked=False,provisional=False,
                historical=True,sourceKind='user-alternate-history',
                note='ユーザー設定によるIF振替日程' if '振替' in label else 'ユーザー提供の架空世界線の日程')
all_fixtures=[]
for season,expected in [(2023,59),(2024,70),(2025,63)]:
    fixtures=[]
    if season==2023:
        for line in (SOURCE/'2023-24-user-schedule.txt').read_text().splitlines():
            cells=[x.strip().replace('**','') for x in line.split('|')[1:-1]]
            if len(cells)!=4 or not re.fullmatch(r'\d{1,2}/\d{1,2}',cells[0]): continue
            md,label,opponent,venue=cells
            month,day=map(int,md.split('/'));year=2023 if month>=8 else 2024
            fixtures.append(fixture(season,f'{year}-{month:02d}-{day:02d}',label,opponent,venue))
        fixtures.extend([fixture(season,'2024-01-11','スーペルコパ 準決勝','オサスナ','中立地'),fixture(season,'2024-01-14','スーペルコパ 決勝','レアル・マドリード','中立地')])
    else:
        with (SOURCE/f'{season}-{str(season+1)[-2:]}.csv').open() as f:
            for row in csv.DictReader(f): fixtures.append(fixture(season,row['date'],row['competition'],row['opponent']))
    fixtures.sort(key=lambda f:(f['date'],f['id']))
    assert len(fixtures)==expected,(season,len(fixtures))
    liga=[f for f in fixtures if f['competition']=='La Liga']
    assert sorted(f['round'] for f in liga)==list(range(1,39))
    metadata=dict(season=season,label=f'{season}-{str(season+1)[-2:]}',team='club',matchCount=expected,
                  titleCount={2023:4,2024:7,2025:6}[season],source='ユーザー添付・本文のIF設定',
                  expectedRecord='63勝0分0敗という物語上の前提。各試合のスコアは未入力。' if season==2025 else 'タイトルは物語上の前提。各試合のスコアは未入力。',
                  notes=['実際に開催されなかった勝ち上がりを含むため、現実の公式日程とは区別する。',
                         '会場が元資料にない試合は未設定のまま保持する。',
                         '2025クラブW杯7試合は2024-25シーズンに含む。' if season==2024 else 'スコア・詳細スタッツを自動作成しない。'])
    (ROOT/f'docs/data/fixtures-{season}-{str(season+1)[-2:]}.json').write_text(json.dumps(dict(metadata=metadata,fixtures=fixtures),ensure_ascii=False,indent=2)+'\n')
    all_fixtures.extend(fixtures)
assert len({f['id'] for f in all_fixtures})==192
(ROOT/'docs/historical-data.js').write_text('// Generated by scripts/build_fixtures.py; user-provided alternate-history fixtures.\nconst HISTORICAL_FIXTURES = '+json.dumps(all_fixtures,ensure_ascii=False,separators=(',',':'))+';\n')
print('Compiled 59 + 70 + 63 = 192 fixtures; all three La Liga calendars have rounds 1–38.')
